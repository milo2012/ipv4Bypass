// TopTCP1000 merges the top-100 with extras, deduplicated and sorted.
func TopTCP1000() []int {
	seen := map[int]bool{}
	out := make([]int, 0, 100+len(TopTCP1000Extra))
	for _, p := range append(append([]int{}, TopTCP100...), TopTCP1000Extra...) {
		if !seen[p] {
			seen[p] = true
			out = append(out, p)
		}
	}
	sort.Ints(out)
	return out
}

